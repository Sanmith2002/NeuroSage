def cohorts(b: Builder) -> list[str]:
    return ["ALL"] + b.cohort_names(UNIVERSE)


def cohort_rows(b: Builder, base: dict, pids: set, key: str = "n_participants") -> list[dict]:
    """One row per cohort: participants of ``pids`` inside the baseline universe."""
    rows = []
    for cohort in cohorts(b):
        members = b.members(UNIVERSE, cohort)
        n = len(pids & members)
        rows.append({**base, "cohort": cohort, "n_in_cohort": b.S(len(members)),
                     key: b.part_of(n, len(members)), "pct_of_cohort": b.P(n, len(members))})
    return rows


def newest_per_name(tables: list[TableResult]) -> list[TableResult]:
    """One table per base name: the newest copy, so duplicate downloads are not mixed."""
    best: dict[str, TableResult] = {}
    for t in tables:
        key = classify.norm(t.base_name)
        rank = (t.name_date, t.member.modified, -int(t.table_id[1:]))
        if key not in best or rank > (best[key].name_date, best[key].member.modified, -int(best[key].table_id[1:])):
            best[key] = t
    return [best[k] for k in sorted(best)]


def add_reference(b: Builder, file: str, frame: pd.DataFrame, source: TableResult | None, what: str,
                  generated: bool) -> bool:
    """Queue a file for ``reports/audit/reference/`` if it passes the identifier check."""
    kept, status, coincidences = vet_reference_table(frame, b.ctx.pids.values, skip_generated_columns=generated)
    b.reference_rows.append({
        "table_id": source.table_id if source is not None else "",
        "source": source.member.source if source is not None else "(generated by the audit)",
        "table_name": f"{source.table_name}: {what}" if source is not None else what,
        "n_rows": b.S(len(frame)), "n_columns": len(frame.columns), "status": status,
        "reference_file": "" if kept is None else file,
        "n_numbers_equal_to_an_identifier_by_coincidence": coincidences,
    })
    if kept is not None:
        b.out.reference[file] = kept
    return kept is not None


def not_exported(b: Builder, what: str, reason: str, source: TableResult | None = None) -> None:
    b.reference_rows.append({
        "table_id": source.table_id if source is not None else "", "source": source.member.source if source else "",
        "table_name": source.table_name if source is not None else what, "n_rows": "", "n_columns": "",
        "status": f"not exported: {reason}", "reference_file": "",
        "n_numbers_equal_to_an_identifier_by_coincidence": "",
    })


def pivot_md(frame: pd.DataFrame, index: list[str], value: str, headers: list[str] | None = None) -> str:
    """Markdown table with one column per cohort."""
    if not len(frame):
        return "_None found._\n"
    names = list(dict.fromkeys(frame["cohort"]))
    sizes = frame.drop_duplicates("cohort").set_index("cohort")["n_in_cohort"].to_dict()
    cells: dict[tuple, dict] = {}
    for record in frame.to_dict("records"):
        cells.setdefault(tuple(record[i] for i in index), {})[record["cohort"]] = record[value]
    return md_table((headers or index) + [f"{c} (n = {sizes[c]})" for c in names],
                    [list(key) + [got.get(c, "") for c in names] for key, got in cells.items()])


def at_events(pairs: np.ndarray, codes: np.ndarray) -> set:
    ev, pid = unpack(pairs)
    return set(pid[np.isin(ev, codes)].tolist())


def field_pairs(b: Builder, table: TableResult, concept: tuple[str, str], pattern: str = "") -> tuple[list[str], np.ndarray]:
    """Fields of a table accepted for a concept, and their (event, participant) pairs."""
    fields = sorted(
        f for f, concepts in b.field_concepts.get(table.table_id, {}).items()
        if concept in concepts and (not pattern or re.search(pattern, f))
    )
    if not fields:
        return [], np.empty(0, dtype=np.uint64)
    return fields, np.unique(np.concatenate([b.field_pairs[table.table_id][f] for f in fields]))


def raw_field_pairs(table: TableResult, pattern: str) -> tuple[list[str], np.ndarray]:
    """Same, straight from a table's name-matched columns (used for the curated cut)."""
    fields = sorted(c for c in table.candidates if re.search(pattern, c))
    if not fields:
        return [], np.empty(0, dtype=np.uint64)
    return fields, np.unique(np.concatenate([table.candidates[c]["pairs"] for c in fields]))


