def annotated_dictionary(b: Builder) -> None:
    cfg = b.ov.section("annotated_dictionary")
    patterns = _as_list(cfg.get("table"))
    found = [t for t in b.ctx.tables if matches(patterns, *b.names(t))]
    if not found:
        not_exported(b, "annotated data dictionary", "no table matching the configured pattern is in the download")
        return
    source = max(found, key=lambda t: (t.name_date, t.member.modified))
    if source.captured is None:
        not_exported(b, "annotated data dictionary",
                     "the table was not held in memory (it has a participant-identifier column or exceeds the row limit)",
                     source)
        return
    frame = source.captured.drop(columns=["_pid", "_event"])
    item, module = find_column(frame, "ITM_NAME"), find_column(frame, "MOD_NAME")
    if item is None:
        not_exported(b, "annotated data dictionary", "it has no ITM_NAME column to match variables on", source)
        return
    targets: dict[str, str] = {}
    if b.curated is not None:
        targets.update({c.upper(): "curated cut column" for c in b.curated.columns})
    for t in biospecimen_tables(b):
        targets.update({c.upper(): "biospecimen results column" for c in t.columns})
    by_item = frame[item].astype(str).str.strip().str.upper().map(targets).fillna("")
    by_module = pd.Series("", index=frame.index)
    if module:
        hit = frame[module].astype(str).str.contains(str(cfg.get("module_regex") or "(?!)"), regex=True)
        by_module = hit.map({True: "module name", False: ""})
        counts = frame[module].astype(str).value_counts().sort_index()
        add_reference(b, "annotated_dictionary_modules.csv",
                      pd.DataFrame({"MOD_NAME": counts.index, "n_dictionary_rows": counts.to_numpy()}),
                      source, "annotated dictionary module index", generated=True)
    keep = (by_item != "") | (by_module != "")
    extract = frame[keep].copy()
    extract.insert(0, "matched_by", (by_item[keep] + " " + by_module[keep]).str.strip())
    if not len(extract):
        not_exported(b, "annotated data dictionary rows",
                     "no row matches a curated-cut or biospecimen column name or the configured module names", source)
        return
    add_reference(b, "annotated_dictionary_curated_and_biospecimen.csv", extract, source,
                  "annotated dictionary rows for the curated cut and biospecimen tables", generated=False)


