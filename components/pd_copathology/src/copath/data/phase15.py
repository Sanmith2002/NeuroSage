_CODING_FIELD_RE = re.compile(r"(?i)ATC|WHO.?DRUG|DRUG.?CLASS|RECNO|SEQNO|MED.?CODE|DRUG.?CODE")


def _drug_regex(aliases: list[str]) -> str:
    return r"\b(?:" + "|".join(re.escape(str(a).lower()) for a in aliases) + r")\b"


def medication_audit(b: Builder) -> None:
    lines = ["# Medication and vascular evidence audit", "",
             f"Aggregates only, for the baseline universe; counts below {b.thr} are shown as `<{b.thr}`. "
             "Drug names are matched against the lists in `configs/drug_classes.yaml`; free text is read in "
             "memory and never written. **No label is defined here and no participant-level file is written.**", ""]
    cfg = b.ov.section("medications")
    table = b.pick(_as_list(cfg.get("table")))
    universe = b.universes[UNIVERSE]
    if table is None or table.captured is None or universe is None:
        why = "no medication table matched" if table is None else "the table or the baseline universe is unavailable"
        b.out.texts["medication_vascular_audit.md"] = "\n".join(lines + [f"Not available: {why}.", ""]) + "\n"
        return
    thr = b.thr
    cap = table.captured[table.captured["_pid"] >= 0].copy()
    cap["_in"] = cap["_pid"].isin(universe)

    # ---- a. columns and coding fields
    col_rows = [{
        "column": c, "inferred_dtype": table.cols[c].dtype, "role": table.roles.role_of(c),
        "pct_missing": b.P(table.cols[c].n_blank, table.n_rows),
        "n_distinct": len(table.cols[c].distinct) if table.cols[c].distinct is not None else "over 2000",
        "dictionary_description": b.decoder.describe(c),
        "is_drug_coding_field": bool(_CODING_FIELD_RE.search(c)),
    } for c in table.columns]
    columns_frame = b._frame("medication_columns.csv", col_rows, list(col_rows[0]))
    coding = [r for r in col_rows if r["is_drug_coding_field"]]
    has_atc = any(re.search(r"(?i)ATC|DRUG.?CLASS", r["column"]) for r in col_rows)
    lines += [f"Table: {q(table.table_name)} ({table.table_id}).", "", "## a. Columns", "",
              md_table(["Column", "Type", "Role", "% missing", "Distinct", "Dictionary description", "Drug coding field"],
                       [[q(r["column"]), r["inferred_dtype"], r["role"], r["pct_missing"], r["n_distinct"],
                         r["dictionary_description"], "yes" if r["is_drug_coding_field"] else ""] for r in col_rows])]
    lines += ["Drug-class or ATC code field: " + ("**present**." if has_atc else "**none found**."),
              "WHODrug-related fields: " + (", ".join(q(r["column"]) for r in coding) if coding else "none found")
              + ". Their missingness is in the table above; a drug class must be derived from the drug name.", ""]

    # ---- shared record-level quantities (memory only)
    name_columns = [c for c in (find_column(cap, n) for n in _as_list(cfg.get("name_columns"))) if c]
    names_text = cap[name_columns].astype(str).agg(" | ".join, axis=1).str.lower() if name_columns else pd.Series("", index=cap.index)
    baseline = b._baseline_month()
    start_col, stop_col = find_column(cap, cfg.get("start_date_column")), find_column(cap, cfg.get("stop_date_column"))
    start = month_index(cap[start_col]) if start_col else pd.Series(np.nan, index=cap.index)
    stop = month_index(cap[stop_col]) if stop_col else pd.Series(np.nan, index=cap.index)
    base = cap["_pid"].map(baseline)
    ongoing = ((start <= base) & (stop.isna() | (stop >= base))).to_numpy()
    inside = cap["_in"].to_numpy()
    pid = cap["_pid"].to_numpy()

    def pids_of(mask: np.ndarray) -> set:
        return set(pid[mask & inside].tolist())

    # ---- b. drug-name frequency
    spec = b.ov.drug_classes()
    freq_rows: list[dict] = []
    masks: dict[tuple[str, str], np.ndarray] = {}

    def frequency(kind: str, group: str, drugs: dict) -> None:
        rare_any, rare_on, rare_names, any_all, on_all = set(), set(), 0, set(), set()
        for generic, aliases in drugs.items():
            mask = names_text.str.contains(_drug_regex(_as_list(aliases) or [generic]), regex=True).to_numpy()
            masks[(group, generic)] = mask
            have, have_on = pids_of(mask), pids_of(mask & ongoing)
            if not have:
                continue
            any_all |= have
            on_all |= have_on
            if len(have) < thr:
                rare_names += 1
                rare_any |= have
                rare_on |= have_on
                continue
            emit(kind, group, generic, have, have_on)
        if rare_names:
            emit(kind, group, f"<{thr} other names ({rare_names} name(s) with fewer than {thr} participants each)",
                 rare_any, rare_on)
        emit(kind, group, "(any listed drug in this group)", any_all, on_all)

    def emit(kind: str, group: str, name: str, have: set, have_on: set) -> None:
        for cohort in cohorts(b):
            members = b.members(UNIVERSE, cohort)
            freq_rows.append({
                "kind": kind, "drug_class": group, "drug_name": name, "cohort": cohort,
                "n_in_cohort": b.S(len(members)),
                "n_participants_any_time": b.part_of(len(have & members), len(members)),
                "pct_of_cohort_any_time": b.P(len(have & members), len(members)),
                "n_participants_ongoing_at_baseline": b.part_of(len(have_on & members), len(members)),
            })

    for group, drugs in (spec.get("classes") or {}).items():
        frequency("candidate class", group, drugs or {})
    for group, drugs in (spec.get("flagged") or {}).items():
        frequency("flagged: ambiguous or excluded", group, drugs or {})
    freq = b._frame("medication_drug_name_frequency.csv", freq_rows, [
        "kind", "drug_class", "drug_name", "cohort", "n_in_cohort", "n_participants_any_time",
        "pct_of_cohort_any_time", "n_participants_ongoing_at_baseline"])
    lines += ["## b. Drug-name frequency by candidate class", "",
              "Participants with at least one record naming the drug, at any time. Names are searched in "
              + ", ".join(q(c) for c in name_columns) + f". Names with fewer than {thr} participants are collapsed.", ""]
    for group in (spec.get("classes") or {}):
        part = freq[freq["drug_class"] == group]
        lines += [f"### {group}", "", pivot_md(part, ["drug_name"], "n_participants_any_time", ["Drug name"])]

    # ---- c. flagged drugs and their indications
    categories = {k: re.compile(v, re.I) for k, v in (spec.get("indication_categories") or {}).items()}
    text_col = find_column(cap, cfg.get("indication_text_column"))
    code_col = find_column(cap, cfg.get("indication_code_column"))

    def category(text: str) -> str:
        if not text.strip():
            return "missing"
        return next((name for name, pattern in categories.items() if pattern.search(text)), "other")

    indication = cap[text_col].astype(str).map(category).to_numpy() if text_col else np.full(len(cap), "missing")
    codes = cap[code_col].astype(str).str.replace(r"\.0+$", "", regex=True).to_numpy() if code_col else None
    flag_rows: list[dict] = []
    for group, drugs in (spec.get("flagged") or {}).items():
        entries = [("(all drugs in this group)", np.logical_or.reduce([masks[(group, g)] for g in drugs]))]
        entries += [(g, masks[(group, g)]) for g in drugs if len(pids_of(masks[(group, g)])) >= thr]
        for name, mask in entries:
            for value in list(categories) + ["other", "missing"]:
                hit = mask & (indication == value)
                if not (hit & inside).any():
                    continue
                for row in cohort_rows(b, {"flagged_group": group, "drug_name": name,
                                           "indication_source": "indication text category",
                                           "indication": value}, pids_of(hit)):
                    row["n_records"] = b.S(int((hit & inside).sum())) if row["cohort"] == "ALL" else ""
                    flag_rows.append(row)
            if codes is None:
                continue
            for value in sorted(set(codes[mask & inside])):
                hit = mask & (codes == value)
                label = "missing" if value == "" else (
                    f"{value} = {b.decoder.decode(code_col, value)}" if b.decoder.decode(code_col, value) else printable(value))
                for row in cohort_rows(b, {"flagged_group": group, "drug_name": name,
                                           "indication_source": "indication code", "indication": label}, pids_of(hit)):
                    row["n_records"] = b.S(int((hit & inside).sum())) if row["cohort"] == "ALL" else ""
                    flag_rows.append(row)
    flagged = b._frame("medication_flagged_indications.csv", flag_rows, [
        "flagged_group", "drug_name", "indication_source", "indication", "cohort", "n_in_cohort",
        "n_participants", "pct_of_cohort", "n_records"])
    lines += ["## c. Flagged drugs (ambiguous or excluded) and their indications", "",
              "These drugs are **not** counted in the candidate classes above. Indication categories are "
              "keyword groups over " + (q(text_col) if text_col else "(no indication text column)")
              + "; the first matching category wins, with orthostatic hypotension tested before hypertension.", ""]
    for group in (spec.get("flagged") or {}):
        names = freq[freq["drug_class"] == group]
        lines += [f"### {group}", "", pivot_md(names, ["drug_name"], "n_participants_any_time", ["Drug name"])]
        part = flagged[(flagged["flagged_group"] == group) & (flagged["indication_source"] == "indication text category")]
        lines.append(pivot_md(part, ["drug_name", "indication"], "n_participants", ["Drug", "Indication category"]))
    lines += ["Indication codes for the same drugs are in `medication_flagged_indications.csv`.", ""]

    # ---- d. dates
    n_all = int(inside.sum())
    usable_start, usable_stop = start.notna().to_numpy(), stop.notna().to_numpy()
    has_base = base.notna().to_numpy()
    evaluable = usable_start & has_base
    before = (start <= base).to_numpy()
    stop_before = (stop < base).to_numpy()
    date_rows = []

    def metric(name: str, mask: np.ndarray, denominator: int) -> None:
        n = int((mask & inside).sum())
        date_rows.append({"metric": name, "n_records": b.S(n), "pct_of_records": b.P(n, denominator)})

    metric("records of baseline-universe participants", np.ones(len(cap), dtype=bool), n_all)
    metric("start date usable", usable_start, n_all)
    metric("stop date usable", usable_stop, n_all)
    if find_column(cap, cfg.get("ongoing_column")):
        flag = cap[find_column(cap, cfg.get("ongoing_column"))].astype(str).str.replace(r"\.0+$", "", regex=True)
        metric("ongoing flag recorded", (flag != "").to_numpy(), n_all)
        metric("ongoing flag = 1", (flag == "1").to_numpy(), n_all)
    metric("participant has a baseline date", has_base, n_all)
    metric("rule evaluable (start date usable and baseline date known)", evaluable, n_all)
    n_eval = int((evaluable & inside).sum())
    metric("evaluable: started at/before baseline, no stop date", evaluable & before & ~usable_stop, n_eval)
    metric("evaluable: started at/before baseline, stopped at/after baseline", evaluable & before & usable_stop & ~stop_before, n_eval)
    metric("evaluable: started and stopped before baseline", evaluable & before & stop_before, n_eval)
    metric("evaluable: started after baseline", evaluable & ~before, n_eval)
    dates = b._frame("medication_date_usability.csv", date_rows, ["metric", "n_records", "pct_of_records"])
    lines += ["## d. Start/stop dates and an \"ongoing at baseline\" rule", "",
              f"Start date column: {q(start_col) if start_col else 'none'}; stop date column: "
              f"{q(stop_col) if stop_col else 'none'}. Dates are compared at month precision with the baseline "
              "visit month from the curated cut. The candidate rule used for the `ongoing_at_baseline` counts is: "
              "**start month not later than baseline, and no stop date or a stop month not earlier than "
              "baseline**. A record with a start date but no stop date is therefore treated as ongoing, which "
              "over-counts drugs that were stopped without a recorded stop date.", "",
              md_table(["Metric", "Records", "% of records"],
                       [[r.metric, r.n_records, r.pct_of_records] for r in dates.itertuples()])]

    # ---- e. elevated supine blood pressure
    lines += _elevated_bp(b)
    b.out.texts["medication_vascular_audit.md"] = "\n".join(lines) + "\n"
    del columns_frame


def _elevated_bp(b: Builder) -> list[str]:
    cfg = b.ov.section("vital_signs")
    lines = ["## e. Elevated supine blood pressure at baseline", ""]
    table = b.pick(_as_list(cfg.get("table")), visit=True)
    if table is None or table.captured is None:
        return lines + ["Not available: no vital-signs table with the configured columns.", ""]
    cap = table.captured[table.captured["_pid"] >= 0]
    sbp_col, dbp_col = find_column(cap, cfg.get("supine_sbp_column")), find_column(cap, cfg.get("supine_dbp_column"))
    if not sbp_col or not dbp_col:
        return lines + ["Not available: supine systolic or diastolic column not found.", ""]
    sbp_cut, dbp_cut = float(cfg.get("elevated_sbp", 140)), float(cfg.get("elevated_dbp", 90))
    frame = pd.DataFrame({
        "pid": cap["_pid"].to_numpy(), "event": cap["_event"].to_numpy(),
        "sbp": pd.to_numeric(cap[sbp_col], errors="coerce").to_numpy(),
        "dbp": pd.to_numeric(cap[dbp_col], errors="coerce").to_numpy(),
    })
    frame = frame[frame["sbp"].notna() | frame["dbp"].notna()]

    def per_participant(events: list[str]) -> pd.DataFrame:
        return frame[frame["event"].isin(events)].groupby("pid")[["sbp", "dbp"]].max()

    at_bl, at_sc = per_participant(b.ov.baseline_events), per_participant(b.ov.screening_events)
    at_sc = at_sc[~at_sc.index.isin(at_bl.index)]
    used = pd.concat([at_bl, at_sc])
    elevated = set(used[(used["sbp"] >= sbp_cut) | (used["dbp"] >= dbp_cut)].index.tolist())
    from_bl, from_sc = set(at_bl.index.tolist()), set(at_sc.index.tolist())
    rows = []
    for cohort in cohorts(b):
        members = b.members(UNIVERSE, cohort)
        measured = (from_bl | from_sc) & members
        rows.append({
            "cohort": cohort, "n_in_cohort": b.S(len(members)),
            "n_measured_at_baseline": b.part_of(len(from_bl & members), len(members)),
            "n_measured_at_screening_because_baseline_missing": b.S(len(from_sc & members)),
            "n_not_measured": b.S(len(members - measured)),
            "n_elevated": b.part_of(len(elevated & measured), len(measured)),
            "pct_elevated_of_measured": b.P(len(elevated & measured), len(measured)),
        })
    out = b._frame("supine_bp_elevated_by_cohort.csv", rows, list(rows[0]))
    lines += [f"Elevated means supine systolic >= {sbp_cut:g} or diastolic >= {dbp_cut:g} mmHg ({q(sbp_col)}, "
              f"{q(dbp_col)} in {q(table.table_name)}). The baseline measurement is used; the screening "
              "measurement is used only when there is none at baseline. If a visit has more than one record the "
              "highest value is taken. This is a descriptive percentage, not a label.", "",
              md_table(["Cohort", "In cohort", "Measured at BL", "Measured at SC only", "Not measured", "Elevated",
                        "% elevated of measured"],
                       [[r.cohort, r.n_in_cohort, r.n_measured_at_baseline,
                         r.n_measured_at_screening_because_baseline_missing, r.n_not_measured, r.n_elevated,
                         r.pct_elevated_of_measured] for r in out.itertuples()])]
    return lines


