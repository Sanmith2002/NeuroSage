def group_members(b: Builder, spec: dict, labels: list[str]) -> set:
    tables, modalities, matrix = _as_list(spec.get("tables")), set(_as_list(spec.get("modalities"))), spec.get("matrix")
    members: set = set()
    for t in b.data:
        if t.table_id in b.excluded or (tables and not matches(tables, *b.names(t))):
            continue
        if matrix:
            if t.long is None or not len(t.long.triples):
                continue
            frame = t.long.participants_by_combo_event()
            keep = [i for i, combo in enumerate(t.long.combos) if re.search(matrix, combo[1])]
            frame = frame[frame["combo"].isin(keep)]
            if b.visit_based(t):
                frame = frame[frame["event"].isin(b.event_codes(labels))]
            members |= set(frame["pid"].unique().tolist())
            continue
        for modality, pids in b.table_sets(t, labels).items():
            if not modalities or modality in modalities:
                members |= pids
    return members


def bl_overlap(b: Builder) -> None:
    columns = ["universe", "cohort", "window", "kind", "combination", "n_modalities", "n_participants",
               "n_in_universe", "pct_of_universe"]
    specs = b.ov.raw.get("bl_overlap_groups") or {}
    if b.universes[UNIVERSE] is None or not specs:
        b._frame("bl_modality_overlap_by_cohort.csv", [], columns)
        return
    events = list(dict.fromkeys(b.ov.screening_events + b.ov.baseline_events))
    window = "baseline window (" + " or ".join(events) + ")"
    groups = {name: group_members(b, spec or {}, events) for name, spec in specs.items()}
    requested = [combo for combo in (b.ov.raw.get("bl_overlap_requested") or []) if all(g in groups for g in combo)]
    rows: list[dict] = []
    for cohort in cohorts(b):
        block, upset = b._overlap_block(UNIVERSE, cohort, window, b.members(UNIVERSE, cohort), groups, True, requested)
        rows += block
        upset["title"] = (f"Baseline universe, cohort {cohort}: participants by exact combination of "
                          f"modalities with data at {' or '.join(events)}")
        slug = re.sub(r"[^a-z0-9]+", "_", cohort.lower()).strip("_") or "cohort"
        b.out.upsets[f"bl_modality_overlap_{slug}.png"] = upset
    b._frame("bl_modality_overlap_by_cohort.csv", rows, columns)


