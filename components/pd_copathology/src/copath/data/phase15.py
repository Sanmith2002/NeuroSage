def biospecimen_tables(b: Builder) -> list[TableResult]:
    patterns = b.ov.patterns("baseline_feasibility", "biospecimen_tables_all")
    return newest_per_name([t for t in b.data if t.long is not None and matches(patterns, *b.names(t))])


def project_names(b: Builder) -> dict[str, str]:
    patterns = b.ov.patterns("baseline_feasibility", "biospecimen_summary_table")
    for t in sorted(b.ctx.tables, key=lambda t: t.name_date, reverse=True):
        if t.captured is None or not matches(patterns, *b.names(t)):
            continue
        project, name = find_column(t.captured, "PROJECTID"), find_column(t.captured, "PROJECT_NAME")
        if project and name:
            return dict(zip(t.captured[project].astype(str).str.strip(), t.captured[name].astype(str).str.strip()))
    return {}


def _safe_label(value: str) -> bool:
    return 0 < len(value) <= 80 and not re.match(classify.DATE_VALUE_RE, value)


def csf_projects(b: Builder) -> None:
    """Tests of each configured CSF project, never pooled, plus between-project overlap at baseline."""
    cfg = b.ov.section("baseline_feasibility")
    projects = _as_list(cfg.get("csf_projects"))
    universe = b.universes[UNIVERSE] or set()
    bl = b.event_codes(b.ov.baseline_events)
    names = project_names(b)
    current = b.pick(_as_list(cfg.get("biospecimen_table")), long=True)
    b.csf = {}
    rows = []
    for t in biospecimen_tables(b):
        wanted = {}
        for idx, (test, matrix, unit, assay) in enumerate(t.long.combos):
            parts = [p.strip() for p in assay.split(" / ")]
            project = next((p for p in projects if p in parts), None)
            if project:
                wanted[idx] = project
        if not wanted:
            continue
        frame = t.long.participants_by_combo_event()
        frame = frame[frame["combo"].isin(wanted)]
        totals: dict[int, int] = {}
        for (combo, _), count in t.long.n_meas.items():
            if combo in wanted:
                totals[combo] = totals.get(combo, 0) + count
        attr_columns = sorted(t.long.attrs)
        fixed = [c for c in t.roles.assay_cols if classify.norm(c) not in {"PROJECTID", "PROJECT_ID"}]
        for idx, part in frame.groupby("combo"):
            test, matrix, unit, _assay = t.long.combos[idx]
            pids = set(part["pid"].tolist())
            at_bl = set(part.loc[part["event"].isin(bl), "pid"].tolist())
            row = {
                "project": wanted[idx], "project_name": names.get(wanted[idx], "(not in the summary table)"),
                "table_name": t.table_name, "status": t.status, "test_name": test,
                "analyte_family": classify.analyte_family(test), "sample_matrix": matrix, "units": unit,
                "is_csf": classify.matrix_modality(matrix, test) == "CSF biomarkers",
                "n_measurements": b.S(totals.get(idx, 0)),
                "n_participants_any_visit": b.S(len(pids)),
                "n_participants_any_visit_in_bl_universe": b.S(len(pids & universe)),
                "n_participants_at_bl_in_bl_universe": b.S(len(at_bl & universe)),
            }
            notes = []
            for column in attr_columns:
                values = t.long.attrs[column].get(idx, set())
                if column in t.roles.date_cols or values is None:
                    row[f"n_distinct_{classify.norm(column).lower()}"] = "many" if values is None else len(values)
                else:
                    shown = sorted(v for v in values if _safe_label(v))
                    notes.append(f"{column}: " + ("; ".join(shown) if 0 < len(shown) <= 4 else f"{len(values)} values"))
            row["assay_fields_in_table"] = "; ".join(notes) or "none"
            row["other_assay_platform_kit_batch_columns"] = (
                ", ".join(fixed) if fixed else "none: the table has no assay, platform, kit or batch column")
            rows.append(row)
        if current is None or t is not current:
            continue
        for project in projects:
            groups = {"abeta": set(), "ptau": set(), "abeta_names": set(), "ptau_names": set()}
            for idx, proj in wanted.items():
                test, matrix, _u, _a = t.long.combos[idx]
                if proj != project or classify.matrix_modality(matrix, test) != "CSF biomarkers":
                    continue
                family = classify.analyte_family(test)
                if family in {"Abeta42", "Abeta (isoform not stated)"}:
                    groups["abeta"].add(idx), groups["abeta_names"].add(test)
                elif family in {"pTau181", "pTau (isoform not stated)"}:
                    groups["ptau"].add(idx), groups["ptau_names"].add(test)
            at = frame[frame["event"].isin(bl)]

            def visits(part: pd.DataFrame, combos: set) -> set:
                part = part[part["combo"].isin(combos)]
                return set(zip(part["event"].tolist(), part["pid"].tolist()))

            abeta_bl, ptau_bl = visits(at, groups["abeta"]), visits(at, groups["ptau"])
            b.csf[project] = {
                "abeta_names": sorted(groups["abeta_names"]), "ptau_names": sorted(groups["ptau_names"]),
                "abeta_bl": {p for _, p in abeta_bl}, "ptau_bl": {p for _, p in ptau_bl},
                "pair_bl": {p for _, p in abeta_bl & ptau_bl},
                "pair_any": {p for _, p in visits(frame, groups["abeta"]) & visits(frame, groups["ptau"])},
                "table": t,
            }
    lead = ["project", "project_name", "table_name", "status", "test_name", "analyte_family", "sample_matrix",
            "units", "is_csf"]
    frame = pd.DataFrame(rows)
    if len(frame):
        extra = [c for c in frame.columns if c not in lead]
        frame = frame[lead + extra].fillna("").sort_values(
            ["project", "table_name", "analyte_family", "test_name", "sample_matrix"], kind="mergesort"
        ).reset_index(drop=True)
        add_reference(b, "csf_assay_project_map.csv", frame, None, "CSF assay project map", generated=True)
    else:
        not_exported(b, "CSF assay project map", "none of the configured projects was found in a biospecimen results table")

    overlap = []
    present = [p for p in projects if p in b.csf]
    for i, first in enumerate(present):
        for second in present[i + 1:]:
            a, c = b.csf[first]["pair_bl"], b.csf[second]["pair_bl"]
            for measure, pids in (
                (f"Abeta + pTau pair at BL in both project {first} and project {second}", a & c),
                (f"Abeta + pTau pair at BL in project {first} only", a - c),
                (f"Abeta + pTau pair at BL in project {second} only", c - a),
                (f"Abeta + pTau pair at BL in project {first} or project {second}", a | c),
            ):
                overlap += cohort_rows(b, {"project_a": first, "project_b": second, "measure": measure}, pids)
    if overlap:
        add_reference(b, "csf_project_overlap_at_bl.csv", pd.DataFrame(overlap), None,
                      "CSF project overlap at baseline", generated=True)
    curated_provenance(b, projects)


def curated_provenance(b: Builder, projects: list[str]) -> None:
    """Which project each curated-cut CSF column comes from, according to the dictionaries."""
    cfg = b.ov.section("baseline_feasibility")
    variables = _as_list(cfg.get("curated_csf_columns"))
    dictionary = next((t for t in b.ctx.tables
                       if t.captured is not None and t.sheet is not None
                       and "dictionary" in t.sheet.lower() and matches(b.ov.reference_tables, *b.names(t))), None)
    curated_columns = {c.lower() for c in b.curated.columns} if b.curated is not None else set()
    test_projects: dict[str, set] = {}
    for t in biospecimen_tables(b):
        for test, _m, _u, assay in t.long.combos:
            test_projects.setdefault(test.strip().lower(), set()).update(p.strip() for p in assay.split(" / ") if p.strip())
    lookup = pd.DataFrame()
    if dictionary is not None:
        lookup = dictionary.captured.drop(columns=["_pid", "_event"]).copy()
        variable = find_column(lookup, "Variable")
        if variable:
            lookup["_variable"] = lookup[variable].astype(str).str.strip().replace("", np.nan).ffill().fillna("").str.lower()
    ids = b.ctx.pids.values
    rows = []
    for name in variables:
        row = {"variable": name, "in_curated_cut": name.lower() in curated_columns,
               "is_biospecimen_test_name": name.lower() in test_projects,
               "biospecimen_projects_with_this_test_name": "; ".join(sorted(test_projects.get(name.lower(), set()))),
               "dictionary_description": "", "dictionary_original_variables": "", "dictionary_original_datasets": "",
               "dictionary_derivation_notes": "", "documented_project": "provenance not documented"}
        if len(lookup) and "_variable" in lookup:
            part = lookup[lookup["_variable"] == name.lower()]
            texts = []
            for key, wanted in (("dictionary_description", "Description"),
                                ("dictionary_original_variables", "Original Variable(s)"),
                                ("dictionary_original_datasets", "Original Dataset(s)"),
                                ("dictionary_derivation_notes", "Derivation Notes")):
                column = find_column(part, wanted)
                value = next((v for v in part[column].astype(str).str.strip() if v), "") if column and len(part) else ""
                if value and reference_table_check(pd.DataFrame({"text": [value]}), ids)[0]:
                    value = "(withheld: failed the identifier check)"
                row[key] = value
                texts.append(value)
            found = sorted(set(re.findall(r"(?i)project\s*(?:id)?\s*#?\s*(\d{3})\b", " ".join(texts))))
            if found:
                row["documented_project"] = "; ".join(found)
            elif not len(part):
                row["documented_project"] = "provenance not documented (variable not in the curated data dictionary)"
        elif dictionary is None:
            row["documented_project"] = "provenance not documented (curated data dictionary sheet not available)"
        rows.append(row)
    if rows:
        add_reference(b, "curated_csf_column_provenance.csv", pd.DataFrame(rows), None,
                      "curated-cut CSF column provenance", generated=True)


