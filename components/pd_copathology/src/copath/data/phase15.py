STEPS: list[tuple[str, Callable[[Builder], None]]] = [
    ("baseline modality overlap", bl_overlap),
    ("CSF assay project map", csf_projects),
    ("label feasibility at baseline", label_feasibility),
    ("medication and vascular audit", medication_audit),
    ("FS7 white-matter check", fs7_check),
    ("annotated dictionary extract", annotated_dictionary),
]


def run(b: Builder) -> None:
    for name, step in STEPS:
        try:
            step(b)
        except Exception as exc:  # noqa: BLE001 - one failing output must not stop the others
            b.ctx.errors.append(error_record("", name, "phase 1.5 output", exc))
    b._frame("reference_table_inventory.csv", b.reference_rows, [
        "table_id", "source", "table_name", "n_rows", "n_columns", "status", "reference_file",
        "n_numbers_equal_to_an_identifier_by_coincidence"])


def summary_md(b: Builder) -> list[str]:
    produced = set(b.out.frames) | set(b.out.texts) | {f"reference/{name}" for name in b.out.reference}
    failed = {e["member"] for e in b.ctx.errors if str(e["stage"]).startswith("phase 1.5")}
    lines = ["## Phase 1.5 outputs", "",
             "All computed for the baseline universe (a baseline row in the curated data cut), by cohort.", "",
             md_table(["File", "Status"],
                      [[q(name), "produced" if name in produced else "not produced; see `reference_table_inventory.csv` "
                        "and `audit_errors.csv` for the reason"] for name in EXPECTED])]
    figures = sorted(n for n in b.out.upsets if n.startswith("bl_modality_overlap_"))
    lines += ["Figures: " + (", ".join(q(n) for n in figures) or "none") + ".", ""]
    if failed:
        lines += ["Items that raised an error: " + ", ".join(sorted(failed)) + ".", ""]
    refused = [r for r in b.reference_rows if str(r["status"]).startswith("not exported")]
    if refused:
        lines += ["Reference tables not exported:", ""] + [
            f"- {q(r['table_name'])}: {r['status']}" for r in refused] + [""]
    return lines
