def fs7_check(b: Builder) -> None:
    cfg = b.ov.section("fs7_wm_check")
    wm = re.compile(str(cfg.get("wm_hypointensity_field") or r"(?i)(?<!non_)wm_hypointens"))
    non_wm = re.compile(str(cfg.get("non_wm_hypointensity_field") or r"(?i)non_wm_hypointens"))
    tables = newest_per_name([t for t in b.data if matches(_as_list(cfg.get("tables")), *b.names(t))])
    lines = ["# FreeSurfer (FS7) white-matter hypointensity check", "",
             f"Aggregates only; counts below {b.thr} are shown as `<{b.thr}`. Cerebellar and cerebral "
             "white-matter **volumes** are normal-tissue volumes and are not counted as white-matter lesions.", ""]
    rows, genuine = [], []
    for t in tables:
        found = []
        for col in t.columns:
            if col in t.roles.pid_cols or col in t.roles.visit_cols:
                continue
            if non_wm.search(col):
                kind = "non-WM hypointensity (not a white-matter measure)"
            elif wm.search(col):
                kind = "WM hypointensity"
            elif re.search(r"(?i)white_?matter", col):
                kind = "rejected: white-matter volume, not a lesion measure"
            else:
                continue
            found.append((col, kind))
            pids: set = set()
            if t.captured is not None and col in t.captured:
                cap = t.captured[t.captured["_pid"] >= 0]
                ok = pd.to_numeric(cap[col], errors="coerce").notna()
                if t.roles.visit:
                    ok &= cap["_event"].isin(b.ov.baseline_events)
                pids = set(cap.loc[ok, "_pid"].tolist())
            rows += cohort_rows(b, {"table_name": t.table_name, "field": col, "classification": kind,
                                    "window": " or ".join(b.ov.baseline_events) if t.roles.visit else "no visit column"},
                                pids, key="n_with_value")
            if kind == "WM hypointensity":
                genuine.append((t, col))
        lines += [f"## {q(t.table_name)} ({len(t.columns)} columns)", ""]
        lines.append(md_table(["Field", "Classification"], [[q(c), k] for c, k in found])
                     if found else "No hypointensity or white-matter field in this table.\n")
    frame = b._frame("fs7_wm_hypointensity_coverage.csv", rows, [
        "table_name", "field", "classification", "window", "cohort", "n_in_cohort", "n_with_value", "pct_of_cohort"])
    lines += ["## Conclusion", ""]
    if not tables:
        lines += ["No FS7 table matched the configured patterns.", "", NO_WMH, ""]
    elif genuine:
        lines += ["White-matter hypointensity fields found: " + ", ".join(f"{q(c)} in {q(t.table_name)}" for t, c in genuine)
                  + ".", "",
                  "These are FreeSurfer T1 white-matter **hypointensity** volumes. They are a proxy for white-matter "
                  "lesion burden, not a FLAIR-based WMH measurement, and need a methodological decision before use.", "",
                  "### Baseline coverage by cohort", "",
                  pivot_md(frame[frame["classification"] == "WM hypointensity"], ["table_name", "field"], "n_with_value",
                           ["Table", "Field"])]
    else:
        lines += [NO_WMH, ""]
    b.out.texts["fs7_aseg_wm_check.md"] = "\n".join(lines) + "\n"


