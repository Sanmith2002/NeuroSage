def label_feasibility(b: Builder) -> None:
    columns = ["label", "requirement", "tests_or_fields", "window", "source_table", "cohort", "n_in_cohort",
               "n_participants", "pct_of_cohort"]
    rows: list[dict] = []
    if b.universes[UNIVERSE] is None:
        b._frame("bl_label_feasibility_by_cohort.csv", rows, columns)
        return
    cfg = b.ov.section("baseline_feasibility")
    universe = b.universes[UNIVERSE]
    bl, sc = b.event_codes(b.ov.baseline_events), b.event_codes(b.ov.screening_events)
    bl_name, sc_name = " or ".join(b.ov.baseline_events), " or ".join(b.ov.screening_events)
    either, either_codes = f"{sc_name} or {bl_name}", np.concatenate([sc, bl])

    def add(label: str, requirement: str, detail: str, window: str, pids: set, table: TableResult | None) -> None:
        rows.extend(cohort_rows(b, {
            "label": label, "requirement": requirement, "tests_or_fields": detail, "window": window,
            "source_table": table.table_name if table is not None else ""}, pids))

    def guarded(name: str, fn: Callable[[], None]) -> None:
        try:
            fn()
        except Exception as exc:  # noqa: BLE001 - one failing item must not hide the others
            b.ctx.errors.append(error_record("", name, "phase 1.5: label feasibility", exc))

    def ad_csf() -> None:
        for project, info in getattr(b, "csf", {}).items():
            detail = f"Abeta: {', '.join(info['abeta_names']) or 'none'}; pTau: {', '.join(info['ptau_names']) or 'none'}"
            add("AD-like", f"CSF Abeta + pTau at the same BL event, project {project}", detail, bl_name,
                info["pair_bl"], info["table"])
            add("AD-like", f"CSF Abeta, project {project}", ", ".join(info["abeta_names"]), bl_name,
                info["abeta_bl"], info["table"])
            add("AD-like", f"CSF pTau, project {project}", ", ".join(info["ptau_names"]), bl_name,
                info["ptau_bl"], info["table"])
        present = sorted(getattr(b, "csf", {}))
        for i, first in enumerate(present):
            for second in present[i + 1:]:
                add("AD-like", f"CSF Abeta + pTau pair at BL in both project {first} and project {second}", "",
                    bl_name, b.csf[first]["pair_bl"] & b.csf[second]["pair_bl"], b.csf[first]["table"])

    def plasma_ptau217() -> None:
        current = b.pick(_as_list(cfg.get("biospecimen_table")), long=True)
        pattern = str(cfg.get("plasma_ptau217_test") or "(?i)p[-_ ]*tau[-_ ]*217")
        if current is not None:
            sources: dict[tuple[str, str], set] = {}
            for idx, (test, matrix, _u, assay) in enumerate(current.long.combos):
                if re.search(pattern, test) and re.search(r"(?i)plasma", matrix):
                    sources.setdefault((assay.split(" / ")[0].strip(), test.strip()), set()).add(idx)
            frame = current.long.participants_by_combo_event()
            for (project, test), combos in sorted(sources.items()):
                part = frame[frame["combo"].isin(combos)]
                add("AD-like", f"plasma pTau217, project {project}", test, bl_name,
                    set(part.loc[part["event"].isin(bl), "pid"].tolist()), current)
                add("AD-like", f"plasma pTau217, project {project}", test, "any visit", set(part["pid"].tolist()), current)
        if b.curated is not None:
            for name in sorted(c for c in b.curated.candidates if re.search(str(cfg.get("curated_ptau217_field") or "(?i)ptau_?217"), c)):
                add("AD-like", "plasma pTau217, curated cut column", name, bl_name,
                    at_events(b.curated.candidates[name]["pairs"], bl), b.curated)

    def saa() -> None:
        table = b.pick(_as_list(cfg.get("saa_table")))
        if table is None or table.captured is None:
            return
        column = find_column(table.captured, cfg.get("saa_status_column"))
        if not column:
            return
        cap = table.captured[(table.captured["_pid"] >= 0) & table.captured["_event"].isin(b.ov.baseline_events)]
        cap = cap[cap[column].astype(str) != ""]
        anyone = set(cap["_pid"].tolist())
        add("PD-type", "alpha-synuclein SAA status available", column, bl_name, anyone, table)
        values = sorted(v for v in set(cap[column].astype(str)) if printable(v) == v)
        if len(values) <= 12:
            for value in values:
                add("PD-type", f"alpha-synuclein SAA status = {value}", column, bl_name,
                    set(cap.loc[cap[column].astype(str) == value, "_pid"].tolist()), table)
        per_pid = cap.groupby("_pid")[column].nunique()
        add("PD-type", "alpha-synuclein SAA: more than one distinct status at BL", column, bl_name,
            set(per_pid[per_pid > 1].index.tolist()), table)
        add("PD-type", "alpha-synuclein SAA status missing", column, bl_name, universe - anyone, table)

    def dat() -> None:
        if b.curated is not None:
            fields, pairs = raw_field_pairs(b.curated, str(cfg.get("curated_dat_field") or "(?i)^MIA_"))
            if fields:
                add("PD-type", "DAT SBR value, curated cut", f"{len(fields)} fields: " + ", ".join(fields[:6]),
                    bl_name, at_events(pairs, bl), b.curated)
        table = b.pick(_as_list(cfg.get("dat_table")), visit=True)
        if table is None:
            return
        fields, pairs = field_pairs(b, table, ("PD-type", "DAT-SPECT"),
                                    str(cfg.get("dat_value_field") or "(?i)caudate|putamen|striatum|sbr"))
        detail = f"{len(fields)} fields"
        if not fields:
            pairs, detail = table.visits[table.roles.visit]["pairs"], "table row (no value field recognised)"
        for window, codes in ((sc_name, sc), (bl_name, bl), (either, either_codes)):
            add("PD-type", "DAT SBR value, core lab", detail, window, at_events(pairs, codes), table)
        add("PD-type", "DAT SBR value, core lab: at SC but not at BL", detail, sc_name,
            at_events(pairs, sc) - at_events(pairs, bl), table)

    def blood_pressure() -> None:
        vit = b.ov.section("vital_signs")
        table = b.pick(_as_list(vit.get("table")), visit=True)
        if table is None:
            return
        got = {}
        for label, name in (("SBP", vit.get("supine_sbp_column")), ("DBP", vit.get("supine_dbp_column"))):
            column = find_column(pd.DataFrame(columns=table.columns), name)
            if column and column in table.candidates:
                got[label] = (column, table.candidates[column]["pairs"])
        for label, (column, pairs) in got.items():
            for window, codes in ((sc_name, sc), (bl_name, bl), (either, either_codes)):
                add("Vascular-risk", f"supine {label} recorded", column, window, at_events(pairs, codes), table)
        if len(got) == 2:
            both = np.intersect1d(got["SBP"][1], got["DBP"][1])
            for window, codes in ((sc_name, sc), (bl_name, bl), (either, either_codes)):
                add("Vascular-risk", "supine SBP and DBP recorded at the same visit",
                    f"{got['SBP'][0]}, {got['DBP'][0]}", window, at_events(both, codes), table)

    def apoe_and_moca() -> None:
        for concept, what in ((("AD-like", "APOE"), "APOE genotype"), (("AD-like", "MoCA"), "MoCA")):
            for t in b.data:
                if t.table_id in b.excluded:
                    continue
                fields, pairs = field_pairs(b, t, concept)
                if not fields:
                    continue
                if concept[1] == "APOE" or not b.visit_based(t):
                    add("AD-like", f"{what} field", ", ".join(fields[:6]), "any visit", set(unpack(pairs)[1].tolist()), t)
                else:
                    for window, codes in ((sc_name, sc), (bl_name, bl), (either, either_codes)):
                        add("AD-like", f"{what} field", ", ".join(fields[:6]), window, at_events(pairs, codes), t)
        current = b.pick(_as_list(cfg.get("biospecimen_table")), long=True)
        if current is not None:
            combos = {i for i, c in enumerate(current.long.combos)
                      if any(r.concept == "APOE" for r in classify.match_test(c[0]))}
            if combos:
                frame = current.long.participants_by_combo_event()
                names = sorted({current.long.combos[i][0] for i in combos})
                add("AD-like", "APOE genotype test (biospecimen results)", ", ".join(names[:6]), "any visit",
                    set(frame.loc[frame["combo"].isin(combos), "pid"].tolist()), current)
        if b.curated is not None:
            for key, what, window in (("curated_apoe_field", "APOE genotype, curated cut column", "any visit"),
                                      ("curated_moca_field", "MoCA, curated cut column", bl_name)):
                fields, pairs = raw_field_pairs(b.curated, str(cfg.get(key) or "(?!)"))
                if fields:
                    pids = at_events(pairs, bl) if window == bl_name else set(unpack(pairs)[1].tolist())
                    add("AD-like", what, ", ".join(fields), window, pids, b.curated)

    def vascular() -> None:
        for (source, concept), (before, table) in sorted(b.vascular_sets.items(), key=lambda kv: kv[0]):
            if "every code" not in source:
                add("Vascular-risk", f"{concept} [{source}]", "", "at or before baseline", before, table)
        table = b.pick(_as_list(cfg.get("wmh_table")))
        if table is not None:
            fields, pairs = field_pairs(b, table, ("Vascular-risk", "WMH / vascular MRI"))
            b.wmh_fields, b.wmh_table = fields, table
            if fields:
                pids = at_events(pairs, bl) if table.roles.visit else set(unpack(pairs)[1].tolist())
                add("Vascular-risk", "white-matter hypointensity volume (FreeSurfer)", ", ".join(fields),
                    bl_name if table.roles.visit else "no visit column", pids, table)

    for name, fn in (("CSF Abeta + pTau by project", ad_csf), ("plasma pTau217", plasma_ptau217), ("SAA status", saa),
                     ("DAT", dat), ("supine blood pressure", blood_pressure), ("APOE and MoCA", apoe_and_moca),
                     ("vascular concepts", vascular)):
        guarded(name, fn)
    b._frame("bl_label_feasibility_by_cohort.csv", rows, columns)


